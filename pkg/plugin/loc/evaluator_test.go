func TestEvaluatorReportsAnUnavailableWorkingDirectory(t *testing.T) {
	evaluator, err := NewEvaluator(DefaultConfiguration())
	if err != nil {
		t.Fatalf("create LOC evaluator: %v", err)
	}
	originalDirectory, err := os.Getwd()
	if err != nil {
		t.Fatalf("read the working directory: %v", err)
	}
	removedDirectory := t.TempDir()
	if err := os.Chdir(removedDirectory); err != nil {
		t.Fatalf("change the working directory: %v", err)
	}
	t.Cleanup(func() {
		if err := os.Chdir(originalDirectory); err != nil {
			t.Errorf("restore the working directory: %v", err)
		}
	})
	if err := os.Remove(removedDirectory); err != nil {
		t.Fatalf("remove the working directory: %v", err)
	}

	_, err = evaluator.Evaluate(t.Context(), plugin.Request{})

	if !errors.Is(err, failure.ErrInternal) {
		t.Errorf("the missing working directory reports %v, want an internal failure", err)
	}
}

