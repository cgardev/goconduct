func TestEvaluatorCreatesFindingsFromPathPolicies(t *testing.T) {
	configuration := fixtureConfiguration()
	configuration.Policies = []policy.PathPolicy{{
		ID:      "small-main-functions",
		Include: []string{"main.go"},
		Thresholds: []policy.Threshold{{
			Metric: "loc.function.lines.code", Comparison: policy.ComparisonMaximum,
			Value: 2, Severity: plugin.SeverityError,
		}},
	}}
	evaluator, err := NewEvaluator(configuration)
	if err != nil {
		t.Fatalf("create LOC evaluator: %v", err)
	}

	report, err := evaluator.Evaluate(t.Context(), plugin.Request{RepositoryRoot: locFixtureRoot(t)})
	if err != nil {
		t.Fatalf("evaluate LOC policy: %v", err)
	}

	if len(report.Findings) != 1 {
		t.Fatalf("the policy reports %d findings, want 1", len(report.Findings))
	}
	finding := report.Findings[0]
	if finding.Path != "main.go" || finding.Actual == nil || *finding.Actual != 3 ||
		finding.Limit == nil || *finding.Limit != 2 {
		t.Errorf("the policy finding is %+v", finding)
	}
}

