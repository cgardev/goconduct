type pathSelectorFunc func(repositoryPath string) (bool, error)

func (selector pathSelectorFunc) Select(repositoryPath string) (bool, error) {
	return selector(repositoryPath)
}

func locFixtureRoot(t *testing.T) string {
	t.Helper()
	return materializeFixture(t, "repository")
}

func materializeFixture(t *testing.T, name string) string {
	t.Helper()
	sourceRoot := filepath.Join("testdata", name)
	targetRoot := t.TempDir()
	err := filepath.WalkDir(sourceRoot, func(sourcePath string, entry fs.DirEntry, walkError error) error {
		if walkError != nil {
			return walkError
		}
		relative, err := filepath.Rel(sourceRoot, sourcePath)
		if err != nil {
			return err
		}
		targetPath := filepath.Join(targetRoot, relative)
		if entry.IsDir() {
			return os.MkdirAll(targetPath, 0o750)
		}
		if strings.HasSuffix(targetPath, ".gotxt") {
			targetPath = strings.TrimSuffix(targetPath, ".gotxt") + ".go"
		}
		payload, err := os.ReadFile(sourcePath)
		if err != nil {
			return err
		}
		return os.WriteFile(targetPath, payload, 0o600)
	})
	if err != nil {
		t.Fatalf("materialize fixture %q: %v", name, err)
	}
	return targetRoot
}

func fixtureConfiguration() Configuration {
	configuration := DefaultConfiguration()
	configuration.Selection.Exclude = append(
		configuration.Selection.Exclude,
		"internal/skip/**",
	)
	configuration.Generated.HeaderPatterns = []string{"(?m)^// AUTOGENERATED$"}
	configuration.Generated.ForceHandwrittenPaths = []string{"manual.pb.go"}
	return configuration
}

func reportMetric(
	t *testing.T,
	report plugin.Report,
	name string,
	repositoryPath string,
) plugin.Metric {
	t.Helper()
	for _, metric := range report.Metrics {
		if metric.Name == name && metric.Path == repositoryPath {
			return metric
		}
	}
	t.Fatalf("metric %q for %q is absent", name, repositoryPath)
	return plugin.Metric{}
}

func TestEvaluatorReportsRepositoryModulePackageFileAndFunctionMetrics(t *testing.T) {
	evaluator, err := NewEvaluator(fixtureConfiguration())
	if err != nil {
		t.Fatalf("create LOC evaluator: %v", err)
	}

	report, err := evaluator.Evaluate(t.Context(), plugin.Request{RepositoryRoot: locFixtureRoot(t)})
	if err != nil {
		t.Fatalf("evaluate LOC fixture: %v", err)
	}

	wants := map[string]float64{
		"loc.repository.files.total":         7,
		"loc.repository.files.test":          1,
		"loc.repository.files.generated":     3,
		"loc.repository.lines.total":         25,
		"loc.repository.lines.code":          16,
		"loc.repository.lines.comment":       3,
		"loc.repository.lines.blank":         6,
		"loc.repository.lines.test":          3,
		"loc.repository.lines.generated":     10,
		"loc.repository.functions.total":     7,
		"loc.repository.functions.test":      1,
		"loc.repository.functions.generated": 3,
	}
	for name, want := range wants {
		if got := reportMetric(t, report, name, "").Value; got != want {
			t.Errorf("metric %s is %.2f, want %.2f", name, got, want)
		}
	}
	if got := reportMetric(t, report, "loc.module.functions.total", "go.mod").Value; got != 6 {
		t.Errorf("the root module reports %.2f functions, want 6", got)
	}
	if got := reportMetric(t, report, "loc.module.functions.total", "tools/go.mod").Value; got != 1 {
		t.Errorf("the nested module reports %.2f functions, want 1", got)
	}
	if got := reportMetric(t, report, "loc.package.functions.total", "internal/protogen").Value; got != 1 {
		t.Errorf("the protobuf package reports %.2f functions, want 1", got)
	}
	if got := reportMetric(t, report, "loc.file.files.generated", "manual.pb.go").Value; got != 0 {
		t.Errorf("the manual override reports %.2f generated files, want 0", got)
	}
	if got := reportMetric(t, report, "loc.file.files.generated", "generated/custom.go").Value; got != 1 {
		t.Errorf("the custom marker reports %.2f generated files, want 1", got)
	}
	if got := reportMetric(t, report, "loc.file.files.generated", "internal/protogen/message.pb.go").Value; got != 1 {
		t.Errorf("the protobuf path reports %.2f generated files, want 1", got)
	}
	if got := reportMetric(t, report, "loc.function.lines.code", "main.go").Value; got != 3 {
		t.Errorf("the Main function reports %.2f code lines, want 3", got)
	}
	for _, metric := range report.Metrics {
		if strings.Contains(metric.Path, "internal/skip") || strings.Contains(metric.Path, "fixtures/testdata") {
			t.Errorf("excluded path reached the report: %+v", metric)
		}
		if strings.HasPrefix(metric.Name, "loc.file.function-lines.") {
			t.Errorf("a file received aggregate function statistics: %+v", metric)
		}
	}
}

func TestGeneratedClassifierReturnsInvalidPathFailures(t *testing.T) {
	tests := []GeneratedConfiguration{
		{ForceHandwrittenPaths: []string{"**/*.go"}},
		{PathPatterns: []string{"**/*.go"}},
	}
	for _, configuration := range tests {
		classifier, err := newGeneratedClassifier(configuration)
		if err != nil {
			t.Fatalf("create generated classifier: %v", err)
		}

		generated, err := classifier.classify("../outside.go", goloc.File{})
		if generated {
			t.Error("the classifier marks an invalid path as generated")
		}

		if !errors.Is(err, failure.ErrValidation) {
			t.Errorf("the classifier reports %v, want a validation failure", err)
		}
	}
}

func TestMetricCalculationsHandleEmptyAndPopulatedSets(t *testing.T) {
	if got := percentage(4, 0); got != 0 {
		t.Errorf("percentage with no denominator is %.2f", got)
	}
	if got := percentage(1, 4); got != 25 {
		t.Errorf("percentage is %.2f, want 25", got)
	}
	average, percentile95, maximum := functionLineStatistics(nil)
	if average != 0 || percentile95 != 0 || maximum != 0 {
		t.Errorf("empty statistics are %.2f, %d, %d", average, percentile95, maximum)
	}
	average, percentile95, maximum = functionLineStatistics([]int{1, 3, 2})
	if average != 2 || percentile95 != 3 || maximum != 3 {
		t.Errorf("statistics are %.2f, %d, %d", average, percentile95, maximum)
	}
}

