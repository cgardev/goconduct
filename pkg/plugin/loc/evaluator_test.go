func TestMeasureFilesReturnsSelectionAndClassificationFailures(t *testing.T) {
	t.Run("a selection failure", func(t *testing.T) {
		evaluator, err := NewEvaluator(DefaultConfiguration())
		if err != nil {
			t.Fatalf("create LOC evaluator: %v", err)
		}
		evaluator.selector = pathSelectorFunc(func(string) (bool, error) {
			return false, failure.Validation("select source path", nil)
		})

		_, err = evaluator.measureFiles(t.Context(), t.TempDir(), []string{"sample.go"})

		if !errors.Is(err, failure.ErrValidation) {
			t.Errorf("the selector reports %v, want a validation failure", err)
		}
	})

	t.Run("a generated classification failure", func(t *testing.T) {
		configuration := DefaultConfiguration()
		configuration.Generated.ForceHandwrittenPaths = []string{"**/*.go"}
		evaluator, err := NewEvaluator(configuration)
		if err != nil {
			t.Fatalf("create LOC evaluator: %v", err)
		}
		evaluator.selector = pathSelectorFunc(func(string) (bool, error) { return true, nil })
		parentDirectory := t.TempDir()
		repositoryRoot := filepath.Join(parentDirectory, "repository")
		if err := os.Mkdir(repositoryRoot, 0o750); err != nil {
			t.Fatalf("create repository root: %v", err)
		}
		source, err := os.ReadFile(filepath.Join("testdata", "repository", "main.gotxt"))
		if err != nil {
			t.Fatalf("read source fixture: %v", err)
		}
		if err := os.WriteFile(filepath.Join(parentDirectory, "outside.go"), source, 0o600); err != nil {
			t.Fatalf("write temporary source: %v", err)
		}

		_, err = evaluator.measureFiles(t.Context(), repositoryRoot, []string{"../outside.go"})

		if !errors.Is(err, failure.ErrValidation) {
			t.Errorf("the classifier reports %v, want a validation failure", err)
		}
	})
}

func TestLocateModuleRejectsInvalidAndUnreadableModuleFiles(t *testing.T) {
	t.Run("a missing module path", func(t *testing.T) {
		repositoryRoot := t.TempDir()
		if err := os.WriteFile(filepath.Join(repositoryRoot, "go.mod"), []byte("go 1.26\n"), 0o600); err != nil {
			t.Fatalf("write module file: %v", err)
		}

		_, err := locateModule(repositoryRoot, "sample.go", make(map[string]moduleDescriptor))

		if !errors.Is(err, failure.ErrDataIntegrity) {
			t.Errorf("the missing module path reports %v, want a data integrity failure", err)
		}
	})

	t.Run("an unreadable module file", func(t *testing.T) {
		repositoryRoot := t.TempDir()
		if err := os.Mkdir(filepath.Join(repositoryRoot, "go.mod"), 0o750); err != nil {
			t.Fatalf("create module directory: %v", err)
		}

		_, err := locateModule(repositoryRoot, "sample.go", make(map[string]moduleDescriptor))

		if !errors.Is(err, failure.ErrUnavailable) {
			t.Errorf("the unreadable module reports %v, want an unavailable failure", err)
		}
	})
}
