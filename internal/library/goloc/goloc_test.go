func TestReceiverNameReadsSupportedSyntaxShapes(t *testing.T) {
	tests := []struct {
		name       string
		expression ast.Expr
		want       string
	}{
		{name: "an identifier", expression: ast.NewIdent("Sample"), want: "Sample"},
		{
			name:       "a pointer",
			expression: &ast.StarExpr{X: ast.NewIdent("Sample")},
			want:       "Sample",
		},
		{
			name:       "a generic receiver with one argument",
			expression: &ast.IndexExpr{X: ast.NewIdent("Sample"), Index: ast.NewIdent("T")},
			want:       "Sample",
		},
		{
			name: "a generic receiver with several arguments",
			expression: &ast.IndexListExpr{
				X:       ast.NewIdent("Sample"),
				Indices: []ast.Expr{ast.NewIdent("T"), ast.NewIdent("U")},
			},
			want: "Sample",
		},
		{
			name: "a qualified receiver",
			expression: &ast.SelectorExpr{
				X:   ast.NewIdent("sample"),
				Sel: ast.NewIdent("Type"),
			},
			want: "sample.Type",
		},
		{
			name:       "a parenthesized receiver",
			expression: &ast.ParenExpr{X: ast.NewIdent("Sample")},
			want:       "Sample",
		},
		{name: "an unsupported receiver", expression: &ast.ArrayType{}, want: "?"},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			if got := receiverName(testCase.expression); got != testCase.want {
				t.Errorf("receiver name is %q, want %q", got, testCase.want)
			}
		})
	}
}

func TestAnalyzeClassifiesPhysicalLinesAndDeclaredFunctions(t *testing.T) {
	path := filepath.Join("testdata", "classification.gotxt")

	result, err := Analyze(path)
	if err != nil {
		t.Fatalf("analyze Go source: %v", err)
	}

	if result.Package != "sample" || !result.StandardGenerated {
		t.Errorf("the file metadata is %+v", result)
	}
	if result.Lines != (Lines{Total: 17, Code: 10, Comment: 3, Blank: 4}) {
		t.Errorf("the file lines are %+v", result.Lines)
	}
	if !slices.EqualFunc(result.Functions, []Function{
		{
			Name: "First", StartLine: 5, EndLine: 12, HasBody: true,
			Lines: Lines{Total: 8, Code: 6, Comment: 1, Blank: 1},
		},
		{
			Name: "Sample.Method", StartLine: 16, EndLine: 16, HasBody: true,
			Lines: Lines{Total: 1, Code: 1},
		},
		{
			Name: "external", StartLine: 17, EndLine: 17, HasBody: false,
			Lines: Lines{Total: 1, Code: 1},
		},
	}, func(left, right Function) bool { return left == right }) {
		t.Errorf("the functions are %+v", result.Functions)
	}
	if result.Header != "// Code generated by sample. DO NOT EDIT.\n" {
		t.Errorf("the normalized header is %q", result.Header)
	}
}

func TestAnalyzeDoesNotTreatCommentTextInsideAStringAsAComment(t *testing.T) {
	path := filepath.Join(t.TempDir(), "string.go")
	source := "package sample\nvar value = \"// not a comment\"\n"
	if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
		t.Fatalf("write Go source: %v", err)
	}

	result, err := Analyze(path)
	if err != nil {
		t.Fatalf("analyze Go source: %v", err)
	}

	if result.Lines != (Lines{Total: 2, Code: 2}) {
		t.Errorf("the file lines are %+v", result.Lines)
	}
}

func TestAnalyzeClassifiesUnreadableAndInvalidSources(t *testing.T) {
	if _, err := Analyze(filepath.Join(t.TempDir(), "absent.go")); !errors.Is(err, failure.ErrUnavailable) {
		t.Errorf("the absent source reports %v, want an unavailable failure", err)
	}
	path := filepath.Join(t.TempDir(), "invalid.go")
	if err := os.WriteFile(path, []byte("package"), 0o600); err != nil {
		t.Fatalf("write invalid source: %v", err)
	}
	if _, err := Analyze(path); !errors.Is(err, failure.ErrDataIntegrity) {
		t.Errorf("the invalid source reports %v, want a data integrity failure", err)
	}
}

func TestPhysicalLineCountHandlesEmptyAndTerminatedSources(t *testing.T) {
	tests := []struct {
		name   string
		source string
		want   int
	}{
		{name: "an empty source", want: 0},
		{name: "one terminated line", source: "package sample\n", want: 1},
		{name: "one unterminated line", source: "package sample", want: 1},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			if got := physicalLineCount([]byte(testCase.source)); got != testCase.want {
				t.Errorf("the line count is %d, want %d", got, testCase.want)
			}
		})
	}
}

func TestSummarizeLinesRejectsInvalidRanges(t *testing.T) {
	contents := []lineContent{{code: true}, {comment: true}}
	tests := []struct {
		name      string
		contents  []lineContent
		startLine int
		endLine   int
	}{
		{name: "an empty source", startLine: 1, endLine: 1},
		{name: "a start before the source", contents: contents, startLine: 0, endLine: 1},
		{name: "an end before the start", contents: contents, startLine: 2, endLine: 0},
	}
	for _, testCase := range tests {
		t.Run(testCase.name, func(t *testing.T) {
			got := summarizeLines(testCase.contents, testCase.startLine, testCase.endLine)
			if got != (Lines{}) {
				t.Errorf("the invalid range reports %+v", got)
			}
		})
	}
}

func TestSummarizeLinesAcceptsOneLine(t *testing.T) {
	contents := []lineContent{{code: true}}
	if got := summarizeLines(contents, 1, 1); got != (Lines{Total: 1, Code: 1}) {
		t.Errorf("the one-line summary reports %+v", got)
	}
}

